# PlatformIO pre-build script: writes src/buildinfo.cpp with the firmware version
# (git describe) and the build time, so they can be shown in /api/state and the web
# app. Only this small file is recompiled on every build; flags stay unchanged so
# the rest of the project is not rebuilt.
Import("env")
import os, subprocess, datetime

root = env.subst("$PROJECT_DIR")

def git(*args):
    try:
        return subprocess.check_output(["git", *args], cwd=root, stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ""

# A CI build of a tag uses that tag: with several tags on one commit (v1.1.3 and
# v1.1.4) plain git describe may pick the other one.
tag = os.environ.get("GITHUB_REF_NAME", "") if os.environ.get("GITHUB_REF_TYPE") == "tag" else ""
version = (tag and git("describe", "--tags", "--always", "--dirty", "--match", tag)) \
    or git("describe", "--tags", "--always", "--dirty") or "unknown"
branch = git("rev-parse", "--abbrev-ref", "HEAD") or "unknown"
built = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
pio_env = env.subst("$PIOENV")
stove_model = (env.GetProjectOption("custom_stove_model", "") or "unknown").replace('"', "'")
# Board the image is for, from the build flag that selects it in src/board.h (BOARD_NAME there)
# (build_flags as written: a pre: script runs before they are parsed into CPPDEFINES)
flags = " ".join(env.get("BUILD_FLAGS", [])).split()
board = "opb-s3" if "-DBOARD_OPB_S3" in flags else "esp32-devkit"

content = f'''// Generated by scripts/buildinfo.py on every build - do not edit, not in git.
// extern: a namespace-scope const has internal linkage in C++ otherwise.
extern const char* const BUILD_VERSION = "{version}";
extern const char* const BUILD_BRANCH  = "{branch}";
extern const char* const BUILD_TIME    = "{built}";
extern const char* const BUILD_ENV     = "{pio_env}";
extern const char* const BUILD_STOVE_MODEL = "{stove_model}";
extern const char* const BUILD_BOARD   = "{board}";
'''
path = os.path.join(root, "src", "buildinfo.cpp")
with open(path, "w") as f:
    f.write(content)
print(f"Build info: {version} ({branch}) {built} [{pio_env}] {board} for {stove_model}")
